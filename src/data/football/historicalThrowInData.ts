  if (clean.includes('dortmund') || clean.includes('bvb')) return { profile: VERIFIED_TEAM_THROW_IN_PROFILES['borussia dortmund'], isVerified: true };
  if (clean.includes('inter')) return { profile: VERIFIED_TEAM_THROW_IN_PROFILES['inter milan'], isVerified: true };
  if (clean.includes('milan') && !clean.includes('inter')) return { profile: VERIFIED_TEAM_THROW_IN_PROFILES['ac milan'], isVerified: true };
  if (clean.includes('juve')) return { profile: VERIFIED_TEAM_THROW_IN_PROFILES['juventus'], isVerified: true };
