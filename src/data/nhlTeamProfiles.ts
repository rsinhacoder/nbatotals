export function getNHLTeamProfile(teamNameOrAbbrev: string): NHLTeamMetrics {
  if (!teamNameOrAbbrev) return NHL_TEAM_PROFILES['CAR'];
  const cleaned = teamNameOrAbbrev.trim().toUpperCase();
  if (NHL_TEAM_PROFILES[cleaned]) return NHL_TEAM_PROFILES[cleaned];
  const matchedAbbrev = NHL_ALIASES[cleaned];
  if (matchedAbbrev && NHL_TEAM_PROFILES[matchedAbbrev]) {
    return NHL_TEAM_PROFILES[matchedAbbrev];
  }
  // Fallback: check substrings
  for (const [alias, code] of Object.entries(NHL_ALIASES)) {
    if (cleaned.includes(alias) || alias.includes(cleaned)) {
      if (NHL_TEAM_PROFILES[code]) return NHL_TEAM_PROFILES[code];
    }
  }
  return NHL_TEAM_PROFILES['CAR']; // Safe default
}

export function getAllNHLTeams(): NHLTeamMetrics[] {
  return Object.values(NHL_TEAM_PROFILES);
}
