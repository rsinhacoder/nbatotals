/**
 * Predicts the anticipated lowest regulation quarter for a matchup between two teams
 * based on their combined pace, defensive ratings, and historical lowest-quarter tendencies.
 */
export function calculateMatchupLowestQuarter(awayTeamName: string, homeTeamName: string): number {
  const away = NBA_TEAMS[awayTeamName];
  const home = NBA_TEAMS[homeTeamName];

  if (!away || !home) {
    return 44.5; // league median default
  }

  // Base is the average of both teams' historical lowest quarter tendencies
  const baseLowestQ = (away.avgLowestQuarter + home.avgLowestQuarter) / 2;

  // Pace adjustment factor: League avg pace is ~99.5
  const avgPace = (away.paceRating + home.paceRating) / 2;
  const paceFactor = (avgPace - 99.5) * 0.45;

  // Defensive adjustment: League avg defensive rating is ~111.0
  const avgDef = (away.defensiveRating + home.defensiveRating) / 2;
  const defFactor = (avgDef - 111.0) * 0.25;

  // Home court slight scoring boost
  const homeBoost = 0.2;

  const projectedLowest = baseLowestQ + paceFactor + defFactor + homeBoost;
  return Number(projectedLowest.toFixed(1));
}

