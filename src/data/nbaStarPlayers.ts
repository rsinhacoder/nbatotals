/**
 * Resolves the star player for any team identifier (abbreviation, city, or full name).
 */
export function getStarPlayerForTeam(teamIdentifier: string): NBAStarPlayer {
  const meta = resolveTeamMeta(teamIdentifier);
  if (NBA_STAR_PLAYERS[meta.abbrev]) {
    return NBA_STAR_PLAYERS[meta.abbrev];
  }
  // Fallback to Boston's Jayson Tatum if unknown
  return NBA_STAR_PLAYERS['BOS'];
}
