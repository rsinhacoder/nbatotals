export function getPlayerProfile(nameOrId: string): NBAPlayerProfile | undefined {
  const norm = nameOrId.toLowerCase().replace(/[^a-z0-9]/g, '-');
  if (NBA_PLAYER_PROFILES[norm]) return NBA_PLAYER_PROFILES[norm];
  
  // Search by display name
  const match = Object.values(NBA_PLAYER_PROFILES).find(
    (p) => p.name.toLowerCase() === nameOrId.toLowerCase() ||
           p.id.toLowerCase() === norm ||
           p.name.toLowerCase().includes(nameOrId.toLowerCase())
  );
  return match;
}

export function getAllPlayerProfiles(): NBAPlayerProfile[] {
  return Object.values(NBA_PLAYER_PROFILES);
}

