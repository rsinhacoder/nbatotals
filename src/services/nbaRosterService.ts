// Map ESPN Team ID to Meta
export const ESPN_TEAM_ID_MAP: Record<string, NBATeamMeta> = {};
Object.values(NBA_TEAMS_META).forEach((meta) => {
  ESPN_TEAM_ID_MAP[meta.id] = meta;
  ESPN_TEAM_ID_MAP[meta.abbrev] = meta;
});

// Normalized search helper
export function resolveTeamMeta(identifier: string): NBATeamMeta {
  if (!identifier) return NBA_TEAMS_META['BOS'];
  const trimmed = identifier.trim().toUpperCase();

  // Direct match by abbrev
  if (NBA_TEAMS_META[trimmed]) return NBA_TEAMS_META[trimmed];
  if (ESPN_TEAM_ID_MAP[identifier]) return ESPN_TEAM_ID_MAP[identifier];

  // Common aliases
  if (trimmed === 'GS' || trimmed === 'WARRIORS') return NBA_TEAMS_META['GSW'];
  if (trimmed === 'SA' || trimmed === 'SAN' || trimmed === 'SPURS') return NBA_TEAMS_META['SAS'];
  if (trimmed === 'NO' || trimmed === 'PELICANS') return NBA_TEAMS_META['NOP'];
  if (trimmed === 'NY' || trimmed === 'KNICKS') return NBA_TEAMS_META['NYK'];
  if (trimmed === 'UTAH' || trimmed === 'JAZZ') return NBA_TEAMS_META['UTA'];
  if (trimmed === 'WSH' || trimmed === 'WIZARDS') return NBA_TEAMS_META['WAS'];
  if (trimmed === 'OKC' || trimmed === 'THUNDER') return NBA_TEAMS_META['OKC'];
  if (trimmed === 'LAC' || trimmed === 'CLIPPERS') return NBA_TEAMS_META['LAC'];
  if (trimmed === 'LAL' || trimmed === 'LAKERS') return NBA_TEAMS_META['LAL'];

  const lower = identifier.toLowerCase().trim();

  // 1. Exact match on team full name
  for (const meta of Object.values(NBA_TEAMS_META)) {
    if (meta.name.toLowerCase() === lower) {
      return meta;
    }
  }

  // 2. Exact match on mascot name (e.g. "Thunder", "Celtics", "Clippers")
  for (const meta of Object.values(NBA_TEAMS_META)) {
    const parts = meta.name.toLowerCase().split(' ');
    const mascot = parts[parts.length - 1];
    if (mascot === lower) {
      return meta;
    }
  }

  // 3. Substring match: identifier contains team full name
  for (const meta of Object.values(NBA_TEAMS_META)) {
    if (lower.includes(meta.name.toLowerCase())) {
      return meta;
    }
  }

  // 4. Substring match: identifier contains mascot name
  for (const meta of Object.values(NBA_TEAMS_META)) {
    const parts = meta.name.toLowerCase().split(' ');
    const mascot = parts[parts.length - 1];
    if (mascot.length >= 4 && lower.includes(mascot)) {
      return meta;
    }
  }

  // 5. City match (guarded for length >= 4 to prevent collisions)
  for (const meta of Object.values(NBA_TEAMS_META)) {
    if (meta.city.length >= 4 && lower.includes(meta.city.toLowerCase())) {
      return meta;
    }
  }

  // Fallback default
  return {
    id: '99',
    abbrev: trimmed.slice(0, 3),
    name: identifier,
    city: identifier,
    logo: 'https://a.espncdn.com/i/teamlogos/default-team-logo-500.png',
    primaryColor: '#334155',
  };
}

